export function translate(
  language: UiLanguage,
  key: string,
  values: Record<string, string | number> = {},
): string {
  const template = language === "zh" ? chineseCopy[key] ?? key : englishStatusCopy[key] ?? key;
  // Substitute once: source titles, queries and user content are never translated.
  return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}
