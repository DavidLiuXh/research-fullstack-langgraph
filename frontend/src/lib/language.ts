/** Static UI copy is bilingual; model-generated prose follows the request language. */
export type UiLanguage = "zh" | "en";

export function detectUiLanguage(text: string): UiLanguage {
  const cleaned = text.replace(/```[\s\S]*?```|`[^`]*`|https?:\/\/\S+/g, "");
  const prose = cleaned.replace(/"[^"\n]*"|“[^”\n]*”/g, "").trim() || text;
  if (/[\u3040-\u30ff\uac00-\ud7af]/.test(prose)) return "en";
  const chinese = (prose.match(/[\u3400-\u9fff]/g) || []).length;
  const words = (prose.match(/[A-Za-z]+/g) || []).length;
  return chinese > 0 && chinese >= words ? "zh" : "en";
}

